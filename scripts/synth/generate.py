# ----------------------------------------------------------------------------- recipe: policy applicability

CATEGORIES = ["perishable food", "electronics", "clothing", "furniture", "books", "cosmetics", "toys"]


def recipe_policy(rng, out):
    for i in range(120):
        local = random.Random(f"policy-{i}")
        window = local.choice([14, 30, 60, 90])
        excluded = local.sample(CATEGORIES, 2)
        cat = local.choice(CATEGORIES)
        days_ago = local.choice([3, 10, 20, 35, 45, 75, 120])
        opened = local.random() < 0.5
        policy = f"Returns are accepted within {window} days of delivery for unused items. {excluded[0].capitalize()} and {excluded[1]} cannot be returned. Opened items may be returned only if defective."
        defective = local.random() < 0.4
        facts = f"The customer received a {cat} item {days_ago} days ago. The item is {'opened' if opened else 'unopened'}{' and defective' if defective else ''}. They want to return it."
        eligible = days_ago <= window and cat not in excluded and (not opened or defective)
        state = {"policy": policy, "case": facts} if local.random() < 0.6 else policy + " " + facts
        q = {"type": "noul", "instructions": "Under the policy, is the customer eligible to return the item?", "criteria": {"true": "All policy conditions are met", "false": "At least one condition or exclusion blocks the return"}}
        out.append(record(f"synth-policy-{i}", "policy", "policy", "eligibility", f"policy/{i}", state, {"eligible": q}, {"eligible": eligible}, tier="policy"))
        # choice: which rule blocks
        reason = "eligible" if eligible else ("outside_window" if days_ago > window else ("excluded_category" if cat in excluded else "opened_not_defective"))
        cq = {"type": "choice", "instructions": "What is the outcome of the return request under the policy?", "criteria": {"eligible": "The return is allowed", "outside_window": "Too many days have passed since delivery", "excluded_category": "The item category cannot be returned", "opened_not_defective": "The item was opened and is not defective"}}
        out.append(record(f"synth-policy-{i}-reason", "policy", "policy", "outcome", f"policy/{i}", state, {"outcome": cq}, {"outcome": reason}, tier="policy"))


