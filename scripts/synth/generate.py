def recipe_enum(rng, out):
    for i in range(80):
        local = random.Random(f"enum-{i}")
        name = local.choice(NAMES)
        words = name.split()
        amount = local.choice([840.0, 1240.5, 12840.0, 99.99, 250.0])
        inv = local.randint(1000, 9999)
        month = local.choice(MONTHS)
        day = local.randint(1, 28)
        state_text = f"Invoice #{inv} issued {month} {day}, 2026 to {name} for ${amount:,.2f}, net {local.choice([10, 30, 60])}."
        cands = {name: None}
        # distractor candidates: substrings / other names / shuffled
        if len(words) >= 2:
            cands[" ".join(words[:-1])] = None
            cands[words[0]] = None
        other = local.choice([n for n in NAMES if n != name])
        cands[other] = None
        cands[" ".join(reversed(words))] = None
        cands = shuffled(local, cands)
        state = {"source_text": state_text} if local.random() < 0.6 else state_text
        instr = {"field": {"name": "customer_name", "type": "string", "description": "The organization the invoice was issued to."}, "question": "Which option is the value of `field` in `source_text`?"} if isinstance(state, dict) else "Which option is the name of the customer the invoice was issued to?"
        q = {"type": "choice", "instructions": instr, "criteria": cands}
        out.append(record(f"synth-enum-{i}", "enum_extraction", "enum_extraction", "literal_candidates", f"enum/{i}", state, {"name": q}, {"name": name}, tier="extraction"))
        # noul reference equality
        extracted = str(inv) if local.random() < 0.5 else str(local.randint(1000, 9999))
        nq = {"type": "noul", "instructions": {"field": {"name": "invoice_number", "type": "string"}, "extracted_value": extracted, "question": "Does `extracted_value` match the `field` as it appears in `source_text`?"}}
        st = state if isinstance(state, dict) else {"source_text": state_text}
        out.append(record(f"synth-enum-{i}-ref", "compatibility", "enum_extraction", "reference_equality", f"enum/{i}", st, {"match": nq}, {"match": extracted == str(inv)}, tier="extraction"))
        # carrier extraction from prose
        carrier = local.choice(CARRIERS)
        st2 = f"Order #{local.randint(1000,9999)}. Status: shipped on {day} {month}. Carrier: {carrier}. Tracking updates every evening."
        q2 = {"type": "choice", "instructions": "Which carrier is delivering the order?", "criteria": {c: None for c in CARRIERS}}
        out.append(record(f"synth-enum-{i}-carrier", "enum_extraction", "enum_extraction", "prose_literal", f"enum/{i}", st2, {"carrier": q2}, {"carrier": carrier}, tier="extraction"))


# ----------------------------------------------------------------------------- recipe: numeric / temporal

LEVELS_AMOUNT = ["Under $100", "$100 to $1,000", "$1,000 to $10,000", "$10,000 to $100,000", "Over $100,000"]


def amount_level(v):
    if v < 100:
        return 0
    if v <= 1000:
        return 1
    if v <= 10000:
        return 2
    if v <= 100000:
        return 3
    return 4


def recipe_numeric(rng, out):
    for i in range(120):
        local = random.Random(f"num-{i}")
        v = local.choice([12.5, 45, 99, 100, 240, 850, 1000, 1500, 4200, 9999, 12840, 55000, 100000, 250000, 1200000])
        qty = local.randint(1, 40)
        days = local.choice([10, 30, 60, 90])
        name = local.choice(NAMES)
        text = local.choice([
            f"Invoice to {name}: {qty} units, total ${v:,.2f}, payment due in {days} days.",
            f"The order from {name} totals ${v:,.2f} for {qty} items; net {days}.",
            f"Amount due: ${v:,.2f}. Quantity: {qty}. Terms: net {days}.",
        ])
        state = {"invoice": {"customer": name, "total": v, "quantity": qty, "terms_days": days, "summary": text}} if local.random() < 0.5 else text
        q = {"type": "score", "instructions": {"field": {"name": "amount_due", "type": "number", "unit": "USD"}, "question": "How large is the invoice total?" if isinstance(state, str) else "How large is `invoice.total`?"}, "criteria": LEVELS_AMOUNT}
        out.append(record(f"synth-num-{i}", "numeric", "numeric", "amount_levels", f"num/{i}", state, {"size": q}, {"size": amount_level(v)}, tier="numeric"))
        thr = local.choice([50, 500, 1000, 5000, 20000, 100000])
        cmp_ = local.choice(["greater than", "more than", "at least", "less than", "under", "at most"])
        if cmp_ in ("greater than", "more than"):
            gold = v > thr
        elif cmp_ == "at least":
            gold = v >= thr
        elif cmp_ in ("less than", "under"):
            gold = v < thr
        else:
            gold = v <= thr
        nq = {"type": "noul", "instructions": f"Is the invoice total {cmp_} ${thr:,}?"}
        out.append(record(f"synth-num-{i}-cmp", "numeric", "numeric", "comparison", f"num/{i}", state, {"cmp": nq}, {"cmp": gold}, tier="numeric"))
        # quantity comparison
        qthr = local.choice([5, 10, 20, 30])
        qq = {"type": "noul", "instructions": f"Were more than {qthr} units ordered?"}
        out.append(record(f"synth-num-{i}-qty", "numeric", "numeric", "count_comparison", f"num/{i}", state, {"qty": qq}, {"qty": qty > qthr}, tier="numeric"))
        # terms level (exact match)
        tq = {"type": "score", "instructions": "How many days does the invoice allow for payment?", "criteria": ["Due on receipt", "Net 10", "Net 30", "Net 60", "Net 90"]}
        out.append(record(f"synth-num-{i}-terms", "numeric", "numeric", "exact_level", f"num/{i}", state, {"terms": tq}, {"terms": {10: 1, 30: 2, 60: 3, 90: 4}[days]}, tier="numeric"))


def recipe_temporal(rng, out):
    for i in range(80):
        local = random.Random(f"time-{i}")
        y, m, d = 2026, local.randint(1, 12), local.randint(1, 28)
        due = f"{y}-{m:02d}-{d:02d}"
        due_text = f"{MONTHS[m-1]} {d}, {y}"
        ref_m, ref_d = local.randint(1, 12), local.randint(1, 28)
        ref = f"{y}-{ref_m:02d}-{ref_d:02d}"
        text = local.choice([
            f"Invoice #{local.randint(1000,9999)} is due on {due_text}. Please pay by bank transfer.",
            f"Payment deadline: {due}. Late fees apply after the deadline.",
            f"The order was placed on {due_text} and shipped two days later.",
        ])
        state = {"invoice": {"due_date": due, "note": text}} if local.random() < 0.4 else text
        word = "before" if local.random() < 0.5 else "after"
        gold = (due < ref) if word == "before" else (due > ref)
        q = {"type": "noul", "instructions": f"Is the date mentioned {word} {ref}?"}
        out.append(record(f"synth-time-{i}", "temporal", "temporal", "date_comparison", f"time/{i}", state, {"date": q}, {"date": gold}, tier="temporal"))


