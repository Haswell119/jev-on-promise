def recipe_adequacy(rng, out):
    for qi, (question, good, bad) in enumerate(QA):
        for rep in range(4):
            local = random.Random(f"adq-{qi}-{rep}")
            for kind, ans, gold in (("adequate", good, True), ("off_topic", bad, False), ("partial", good.split(";")[0].split(",")[0] + ".", None)):
                if kind == "partial" and rep > 1:
                    continue
                state = {"question": question, "answer": ans}
                q = {"type": "noul", "instructions": "Does `answer` adequately address `question`?", "criteria": {"true": "The answer directly resolves what was asked", "false": "The answer is off-topic or does not resolve the question"}}
                g = gold if gold is not None else True
                if kind == "partial":
                    continue
                out.append(record(f"synth-adq-{qi}-{rep}-{kind}", "adequacy", "adequacy", kind, f"adq/{qi}", state, {"adequate": q}, {"adequate": g}, tier="adequacy"))
            # relevance choice
            distractor_q = QA[(qi + 1 + rep) % len(QA)][0]
            state = {"query": question, "passages": {"p1": good, "p2": bad}}
            cq = {"type": "choice", "instructions": "Which passage answers `query`?", "criteria": {"p1": None, "p2": None}}
            out.append(record(f"synth-rel-{qi}-{rep}", "relevance", "adequacy", "passage_choice", f"adq/{qi}", state, {"best": cq}, {"best": "p1"}, tier="adequacy"))
            _ = distractor_q


