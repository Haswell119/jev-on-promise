MODEL = "sextant-1"

# ----------------------------------------------------------------------------- helpers

def split_for(group: str) -> str:
    h = int(hashlib.sha256(group.encode()).hexdigest()[:8], 16) % 100
    return "train" if h < 60 else ("calib" if h < 80 else "dev")


def record(rid, family, recipe, transformation, group, state, questions, gold, tier="internal", gold_probs=None, extra=None):
    r = {
        "id": rid,
        "source": f"synthetic/{recipe}",
        "license": "Apache-2.0 (generated by scripts/synth/generate.py)",
        "split": split_for(group),
        "tier": tier,
        "family": family,
        "synthetic": True,
        "transformation": transformation,
        "group": group,
        "recipe": recipe,
        "request": {"model": MODEL, "state": state, "questions": questions},
        "gold": gold,
    }
    if gold_probs:
        r["gold_probs"] = gold_probs
    if extra:
        r.update(extra)
    return r


def shuffled(rng, d):
    items = list(d.items())
    rng.shuffle(items)
    return dict(items)


