"""Synthetic DEVELOPMENT data recipes for Sextant (deterministic, seeded).

Every record is marked `synthetic: true` with its `recipe` and `transformation`.
Labels are programmatically verifiable by construction. Records are split into
train / calib / dev by a hash of their *group* (template family + slot seed), so
paraphrases and permutations of the same scenario never straddle splits.

Usage: python3 scripts/synth/generate.py --seed 20260922 --out data/synthetic
"""
import argparse
