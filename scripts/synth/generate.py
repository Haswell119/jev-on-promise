def fill(rng, t):
    return t.format(
        product=rng.choice(PRODUCTS),
        amount=rng.choice([49, 120, 240, 899, 1240, 3200]),
        order=rng.randint(1000, 99999),
        date=f"{rng.choice(MONTHS)} {rng.randint(1, 28)}",
        carrier=rng.choice(CARRIERS),
        email=f"user{rng.randint(1,999)}@example.com",
        n=rng.choice([12, 25, 50, 120]),
    )


def dept_question(rng, depts, structured):
    crit = {}
    for d in depts:
        info = DEPARTMENTS[d]
        if structured == "object":
            crit[d] = {"what": info["what"], "not_for": info["not_for"], "examples": info["examples"]}
        elif structured == "null":
            crit[d] = None
        else:
            crit[d] = info["what"]
    return {"type": "choice", "instructions": rng.choice(["Which team should handle this message?", "Route this customer message to the right department.", "Which department is responsible for this request?", {"question": "Which team should handle this message?", "focus": "Classify the customer's primary request, not every topic mentioned."}]), "criteria": crit}


def recipe_routing(rng, out):
    depts_all = list(DEPARTMENTS)
    n = 0
    for dept in depts_all:
        for ti, tmpl in enumerate(DEPARTMENTS[dept]["templates"]):
            for rep in range(3):
                seed = rng.random()
                local = random.Random(f"{dept}-{ti}-{rep}-{seed}")
                msg = fill(local, tmpl)
                k = local.choice([4, 5, 6, 8])
                depts = local.sample([d for d in depts_all if d != dept], k - 1) + [dept]
                local.shuffle(depts)
                structured = local.choice(["string", "object", "string"])
                q = dept_question(local, depts, structured)
                group = f"routing/{dept}/{ti}"
                base_id = f"synth-routing-{dept}-{ti}-{rep}"
                out.append(record(base_id, "routing", "routing", "plain", group, msg, {"dept": q}, {"dept": dept}))
                n += 1
                # paraphrase
                if ti < len(PARAPHRASE[dept]):
                    pmsg = fill(local, PARAPHRASE[dept][ti])
                    out.append(record(base_id + "-para", "routing", "routing", "paraphrase", group, pmsg, {"dept": q}, {"dept": dept}))
                    n += 1
                # distractor preamble
                dmsg = local.choice(DISTRACTORS) + " " + msg + " " + local.choice(DISTRACTORS)
                out.append(record(base_id + "-distract", "routing", "routing", "distractor", group, dmsg, {"dept": q}, {"dept": dept}))
                # json wrapped
                jstate = {"ticket": {"id": f"T-{local.randint(100,999)}", "channel": local.choice(["email", "chat", "phone"]), "customer": {"name": local.choice(["A. Lee", "M. Garcia", "S. Okafor"]), "tier": local.choice(["free", "pro"])}, "message": msg}}
                jq = dict(q)
                jq["instructions"] = "Which team should handle `ticket.message`?"
                out.append(record(base_id + "-json", "routing", "routing", "json_wrap", group, jstate, {"dept": jq}, {"dept": dept}))
                # permutation of options (same group; stability metric)
                pq = dict(q)
                pq["criteria"] = shuffled(local, q["criteria"])
                out.append(record(base_id + "-perm", "routing", "routing", "option_permutation", group, msg, {"dept": pq}, {"dept": dept}))
                # injection
                inj = msg + " " + local.choice(INJECTIONS)
                out.append(record(base_id + "-inject", "routing", "routing", "injection", group, inj, {"dept": q}, {"dept": dept}, tier="adversarial"))
                n += 4
    # fallback option: "other" wins for off-topic messages, loses otherwise
    OFFTOPIC = [
        "Do you know a good recipe for banana bread? My oven runs a little hot.",
        "What time does the museum open on Sundays? We are visiting next week.",
        "My neighbor's dog keeps barking at night and I can't sleep.",
        "Could you recommend a novel similar to the one I read last summer?",
        "The football match ended in a draw; the referee was terrible.",
        "Which hiking trails near the lake are open in winter?",
        "I am learning to play the guitar and my fingers hurt.",
        "How many calories are in a bowl of oatmeal with honey?",
    ]
    for i in range(48):
        local = random.Random(f"fallback-{i}")
        depts = local.sample(depts_all, 4)
        crit = {d: DEPARTMENTS[d]["what"] for d in depts}
        fb_key, fb_desc = local.choice([("other", "None of the above; unrelated to our products or services"), ("none_of_the_above", "The message does not fit any listed team"), ("unclear", "Cannot be determined from the message"), ("other", None)])
        crit[fb_key] = fb_desc
        crit = shuffled(local, crit)
        q = {"type": "choice", "instructions": "Which team should handle this message? Pick the fallback option if none applies.", "criteria": crit}
        if i % 2 == 0:
            msg = local.choice(OFFTOPIC)
            gold = fb_key
        else:
            dept = local.choice(depts)
            msg = fill(local, local.choice(DEPARTMENTS[dept]["templates"]))
            gold = dept
        out.append(record(f"synth-routing-fallback-{i}", "routing", "routing", "fallback_option", f"routing/fallback/{i}", msg, {"dept": q}, {"dept": gold}, tier="fallback"))
    # negated contrast
    for i, (neg, real, tmpl) in enumerate(NEGATED_CONTRAST):
        for rep in range(4):
            local = random.Random(f"negc-{i}-{rep}")
            msg = tmpl.format(msg=fill(local, local.choice(DEPARTMENTS[real]["templates"])))
            depts = [neg, real] + local.sample([d for d in depts_all if d not in (neg, real)], 3)
            local.shuffle(depts)
            q = dept_question(local, depts, "string")
            out.append(record(f"synth-routing-negcontrast-{i}-{rep}", "routing", "routing", "negated_contrast", f"routing/negc/{i}/{rep}", msg, {"dept": q}, {"dept": real}, tier="negation"))
    return n


